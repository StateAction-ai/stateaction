#!/usr/bin/env python3
"""Install the local-CI hooks for THIS worktree only.

Shared hooks and the shared core.hooksPath are never modified. The only
repository-wide setting is the standard `extensions.worktreeConfig` switch Git
requires before any setting can be worktree-scoped (left on at uninstall because
other worktrees may use it). The previous hooks directory is recorded, chained by
the generated wrappers and restored by --uninstall; a hooks path somebody else
set after ours is never removed. Idempotent.
"""

from __future__ import annotations

import argparse
import json
import shlex
import subprocess
import sys
from pathlib import Path

HOOKS = ("pre-commit", "pre-push")
WRAPPER = """#!/bin/sh
# Generated by scripts/local-ci/install.py for this worktree. Fails closed if the
# tracked hook is missing, so a branch switch cannot silently disable local CI.
top={top}
hook="$top/scripts/local-ci/hooks/{name}"
if [ ! -x "$hook" ]; then
  echo "local CI hook $hook is missing; re-run scripts/local-ci/install.py" >&2
  exit 1
fi
{previous}exec "$hook" "$@"
"""


def git(repo: Path, *args: str, check=True) -> str:
    result = subprocess.run(["git", *args], cwd=repo, capture_output=True, text=True)
    if check and result.returncode:
        raise SystemExit(f"git {args[0]} failed: {result.stderr.strip()}")
    return result.stdout.strip()


def write_if_changed(path: Path, text: str) -> bool:
    if path.exists() and path.read_text() == text:
        path.chmod(0o755)
        return False
    path.write_text(text)
    path.chmod(0o755)
    return True


def resolve(repo: Path, value: str) -> str:
    path = Path(value).expanduser()
    return str(path if path.is_absolute() else repo / path)


def install(repo: Path) -> dict:
    repo = Path(git(repo, "rev-parse", "--show-toplevel"))
    gitdir = Path(git(repo, "rev-parse", "--absolute-git-dir"))
    directory = gitdir / "stateaction-hooks"
    directory.mkdir(exist_ok=True)
    state_file = directory / "state.json"
    changed = []
    if (
        git(repo, "config", "--bool", "--get", "extensions.worktreeConfig", check=False)
        != "true"
    ):
        git(repo, "config", "extensions.worktreeConfig", "true")
        changed.append("extensions.worktreeConfig")
    current = git(repo, "config", "--worktree", "--get", "core.hooksPath", check=False)
    if current != str(directory):
        effective = git(repo, "config", "--get", "core.hooksPath", check=False)
        state = {
            "previousWorktree": current or None,
            "previousEffective": resolve(repo, effective) if effective else None,
        }
        state_file.write_text(json.dumps(state, indent=2) + "\n")
        git(repo, "config", "--worktree", "core.hooksPath", str(directory))
        changed.append("core.hooksPath(worktree)")
    state = json.loads(state_file.read_text()) if state_file.exists() else {}
    chain = state.get("previousEffective")
    previous = (
        f"STATEACTION_PREVIOUS_HOOKS={shlex.quote(chain)}\nexport STATEACTION_PREVIOUS_HOOKS\n"
        if chain
        else ""
    )
    for name in HOOKS:
        text = WRAPPER.format(top=shlex.quote(str(repo)), name=name, previous=previous)
        if write_if_changed(directory / name, text):
            changed.append(name)
    return {"worktree": str(repo), "hooksPath": str(directory), "changed": changed}


def uninstall(repo: Path) -> dict:
    repo = Path(git(repo, "rev-parse", "--show-toplevel"))
    directory = Path(git(repo, "rev-parse", "--absolute-git-dir")) / "stateaction-hooks"
    current = git(repo, "config", "--worktree", "--get", "core.hooksPath", check=False)
    if current != str(directory):
        return {
            "worktree": str(repo),
            "removed": False,
            "reason": "core.hooksPath is not ours; left untouched",
        }
    state_file = directory / "state.json"
    state = json.loads(state_file.read_text()) if state_file.exists() else {}
    if state.get("previousWorktree"):
        git(repo, "config", "--worktree", "core.hooksPath", state["previousWorktree"])
    else:
        git(repo, "config", "--worktree", "--unset", "core.hooksPath")
    return {
        "worktree": str(repo),
        "removed": True,
        "restored": state.get("previousWorktree"),
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--uninstall", action="store_true")
    parser.add_argument("--repo", type=Path, default=Path.cwd())
    args = parser.parse_args()
    print(
        json.dumps(
            uninstall(args.repo) if args.uninstall else install(args.repo), indent=2
        )
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
