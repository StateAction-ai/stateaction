"""Generate Python and TypeScript static types from the compiled graph schema."""

import json
from pathlib import Path

from catalog import refresh

SCHEMA = Path("packages/contracts/recipe/compiled-graph.v1.schema.json")
TYPESCRIPT = Path("packages/contracts/src/compiled-graph.generated.ts")
PYTHON = Path("core/stateaction_recipes/compiled_graph.py")


def annotation(schema: dict, *, python: bool) -> str:
    if "$ref" in schema:
        return schema["$ref"].removeprefix("#/$defs/")
    if "enum" in schema or "const" in schema:
        values = schema["enum"] if "enum" in schema else [schema["const"]]
        if not python:
            return " | ".join(json.dumps(value) for value in values)
        literals = [repr(value) for value in values if value is not None]
        types = [f"Literal[{', '.join(literals)}]"] if literals else []
        if None in values:
            types.append("None")
        return " | ".join(types)
    if "anyOf" in schema:
        return " | ".join(
            annotation(branch, python=python) for branch in schema["anyOf"]
        )
    kind = schema["type"]
    if isinstance(kind, list):
        return " | ".join(annotation({"type": item}, python=python) for item in kind)
    if kind == "array":
        value = annotation(schema["items"], python=python)
        return f"list[{value}]" if python else f"Array<{value}>"
    if kind == "object":
        value = annotation(schema["additionalProperties"], python=python)
        return f"dict[str, {value}]" if python else f"Record<string, {value}>"
    primitives = {
        "string": ("str", "string"),
        "integer": ("int", "number"),
        "boolean": ("bool", "boolean"),
        "null": ("None", "null"),
    }
    return primitives[kind][0 if python else 1]


def generate(root: Path, *, check: bool) -> None:
    schema = json.loads((root / SCHEMA).read_text())
    origin = f"Generated by recipe sync from {SCHEMA.name}. Do not edit."
    python = [
        "# fmt: off",
        f"# {origin}",
        "from __future__ import annotations",
        "",
        "from typing import Literal, TypedDict",
    ]
    ts = [f"// {origin}"]
    for name, spec in {**schema["$defs"], schema["title"]: schema}.items():
        properties = spec["properties"]
        if set(spec["required"]) != set(properties):
            raise ValueError(
                f"{name}: the graph generator expects required record fields"
            )
        python += ["", f"{name} = TypedDict(", f"    {name!r},", "    {"]
        ts += ["", f"export interface {name} {{"]
        for key, field in properties.items():
            python.append(f"        {key!r}: {annotation(field, python=True)},")
            ts.append(f"  {key}: {annotation(field, python=False)};")
        python += ["    },", ")"]
        ts += ["}"]
    refresh(root / PYTHON, "\n".join(python) + "\n", check=check)
    refresh(root / TYPESCRIPT, "\n".join(ts) + "\n", check=check)
