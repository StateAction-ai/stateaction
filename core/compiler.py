"""Validate sandbox output against trusted module locks and compile a graph."""

import heapq
import json
import re
from decimal import ROUND_CEILING, Decimal
from pathlib import Path

from catalog import (
    ARTIFACT,
    CPU_RATE,
    GPU_RATES,
    ID,
    PARAMETER_TYPES,
    bindings,
    offline_validator,
    parameter_schema,
    sha256,
)
from sandbox import SOURCE_LIMIT, CompileError, canonical_json, read_source, run_sandbox
from types_codegen import SCHEMA

BUILTINS = {
    "recording.source": ("recording_source@2", "recording"),
    "clip.video": ("video_range@1", "clip"),
}


def validate(schema, value, code, fix, line):
    if offline_validator(schema).is_valid(value):
        return
    raise CompileError(code, fix, line)


def resolve(ref, artifact, scope, nodes, line):
    producer, _, port = ref.partition(".") if type(ref) is str else ("", "", "")
    expected = BUILTINS.get(ref) if type(ref) is str else None
    if producer in nodes and port in nodes[producer]["outputs"]:
        node = nodes[producer]
        expected = node["outputs"][port], node["scope"]
    if expected is None or expected[0] != artifact:
        raise CompileError(
            "wrong_edge", f"Pass an output handle of type {artifact}.", line
        )
    if expected[1] != scope:
        raise CompileError(
            "wrong_scope", f"Pass a handle from the {scope} scope.", line
        )
    return producer if producer in nodes else None


def charge_usd(node, source_seconds):
    resources = node["resources"]
    rate = Decimal(GPU_RATES[resources["gpu"]] if resources["gpu"] else CPU_RATE)
    return rate * wall_budget(resources["budget"], source_seconds) / 3600


def wall_budget(work, source_seconds):
    return int(
        (
            work["fixedSeconds"] + Decimal(work["perSourceSecond"]) * source_seconds
        ).to_integral_value(rounding=ROUND_CEILING)
    )


def dollars(amount):
    return format(amount.quantize(Decimal("0.01"), rounding=ROUND_CEILING), ".2f")


def topo_order(nodes, line):
    pending = {node_id: set(node["producers"]) for node_id, node in nodes.items()}
    ready = [node_id for node_id, parents in pending.items() if not parents]
    heapq.heapify(ready)
    order = []
    depth = {}
    while ready:
        node_id = heapq.heappop(ready)
        order.append(node_id)
        depth[node_id] = 1 + max(
            (depth[parent] for parent in nodes[node_id]["producers"]), default=0
        )
        if depth[node_id] > 8:
            raise CompileError(
                "graph_too_deep",
                "Keep the graph at eight nodes of dependency depth or fewer.",
                line,
            )
        for child, parents in pending.items():
            if node_id in parents:
                parents.remove(node_id)
                if not parents:
                    heapq.heappush(ready, child)
    if len(order) != len(nodes):
        raise CompileError(
            "cycle", "Connect nodes to outputs from upstream nodes only.", line
        )
    return order


def node_shell(node, catalog, schema, duration, line):
    lock = catalog.get(node["module"])
    if lock is None:
        raise CompileError(
            "unknown_module", "Import a module binding generated by recipe sync.", line
        )
    manifest = lock["manifest"]
    if node["scope"] != manifest["scope"]:
        raise CompileError(
            "wrong_scope",
            f"Call {manifest['id']} in the {manifest['scope']} scope.",
            line,
        )
    resources = node["resources"]
    allowed = manifest["gpus"] or [None]
    if resources.get("gpu") not in allowed:
        raise CompileError(
            "invalid_gpu", f"Use one of {allowed} for {manifest['id']}.", line
        )
    validate(
        schema["$defs"]["Resources"] | {"$defs": schema["$defs"]},
        resources,
        "invalid_resources",
        "Use budget.fixed or budget.linear with a positive time and a nonnegative slope.",
        line,
    )
    if (
        type(resources["budget"]["fixedSeconds"]) is not int
        or wall_budget(resources["budget"], duration) > manifest["maxBudgetSeconds"]
    ):
        raise CompileError(
            "invalid_budget",
            f"Keep the time budget at or below {manifest['maxBudgetSeconds']} seconds at max source duration.",
            line,
        )
    params = {
        name: spec["default"]
        for name, spec in manifest["params"].items()
        if "default" in spec
    } | node["params"]
    specs = manifest["params"]
    for field in params.keys() & specs.keys():
        if type(params[field]) is not PARAMETER_TYPES[specs[field]["type"]]:
            raise CompileError(
                "invalid_parameter",
                f"Use a {specs[field]['type']} for {field}.",
                line,
            )
    validator = offline_validator(parameter_schema(specs))
    if error := next(validator.iter_errors(params), None):
        field = ".".join(map(str, error.absolute_path)) or "arguments"
        raise CompileError(
            "invalid_parameter",
            f"Check {field} against the {manifest['id']} manifest.",
            line,
        )
    return {
        "scope": node["scope"],
        "module": node["module"],
        "moduleLockSha256": sha256(canonical_json(lock)),
        "params": params,
        "resources": resources,
        "outputs": manifest["outputs"],
    }


def compile_graph(raw, catalog, schema, path, source):
    line = raw["recipeLine"]
    if not re.fullmatch(ARTIFACT, raw["recipe"]):
        raise CompileError(
            "invalid_recipe_id",
            "Use a lowercase id and a positive integer version.",
            line,
        )
    validate(
        schema["$defs"]["Meta"] | {"$defs": schema["$defs"]},
        raw["meta"],
        "invalid_limits",
        "Set a title, nonnegative USD caps and a source duration from 1 to 7200 seconds.",
        line,
    )
    limits = raw["meta"]["limits"]
    duration = limits["maxSourceSeconds"]
    if type(duration) is not int:
        raise CompileError(
            "invalid_limits", "Use a whole number of source seconds.", line
        )
    entries = raw["nodes"]
    if not 1 <= len(entries) <= 32:
        raise CompileError(
            "invalid_node_count", "Declare between 1 and 32 nodes.", line
        )
    locations = raw["nodeSources"]
    nodes = {}
    for node_id, node in entries.items():
        node_line = locations[node_id]
        if node_id in {"clip", "recording"}:
            raise CompileError(
                "reserved_node_id",
                "Choose a node id other than clip or recording.",
                node_line,
            )
        if not re.fullmatch(ID, node_id):
            raise CompileError(
                "invalid_node_id",
                "Use a lowercase id of at most 32 characters.",
                node_line,
            )
        nodes[node_id] = node_shell(node, catalog, schema, duration, node_line)
    fan_out = raw.get("fanOut")
    clips = [node for node in nodes.values() if node["scope"] == "clip"]
    plan_node = None
    if fan_out:
        plan_line = raw["fanOutLine"]
        plan_node = resolve(
            fan_out["clip"], "clip_plan@1", "recording", nodes, plan_line
        )
        if (
            not plan_node
            or not catalog[nodes[plan_node]["module"]]["manifest"]["passthroughPlan"]
        ):
            raise CompileError(
                "invalid_fan_out",
                "Pass the plan from clip_filter_passthrough to per_clip.",
                plan_line,
            )
    if bool(clips) != bool(plan_node):
        raise CompileError(
            "invalid_fan_out",
            "Use one per_clip block when the recipe has clip nodes.",
            line,
        )
    for node_id, node in nodes.items():
        scope = node["scope"]
        node_line = locations[node_id]
        inputs = entries[node_id]["inputs"]
        ports = catalog[node["module"]]["manifest"]["inputs"]
        if inputs.keys() != ports.keys():
            raise CompileError(
                "wrong_ports",
                "Bind the inputs declared in the module manifest.",
                node_line,
            )
        producers = {plan_node} if scope == "clip" else set()
        for port, artifact in ports.items():
            upstream = resolve(inputs[port], artifact, scope, nodes, node_line)
            if upstream:
                producers.add(upstream)
        node["inputs"] = {
            port: {"from": inputs[port], "type": kind} for port, kind in ports.items()
        }
        node["producers"] = sorted(producers)

    order = topo_order(nodes, line)
    cost = {"clip": Decimal(0), "recording": Decimal(0)}
    finish = {}
    noncommercial = set()
    for node_id in order:
        node = nodes[node_id]
        cost[node["scope"]] += charge_usd(node, duration)
        finish[node_id] = wall_budget(node["resources"]["budget"], duration) + max(
            (finish[parent] for parent in node["producers"]), default=0
        )
        if not catalog[node["module"]]["manifest"]["commercialUse"]:
            noncommercial.add(node["module"])
    if Decimal(dollars(cost["clip"])) > Decimal(limits["maxClipJobCostUsd"]):
        raise CompileError(
            "clip_cost_cap",
            "Reduce per-clip budgets or set a higher max_clip_job_cost.",
            line,
        )
    if Decimal(dollars(cost["recording"] + cost["clip"])) > Decimal(
        limits["maxRecordingCostUsd"]
    ):
        raise CompileError(
            "recording_cost_cap",
            "Reduce node budgets or raise max_recording_cost to cover one full-length clip and recording overhead.",
            line,
        )
    critical = max(finish.values())
    if critical > 43200:
        raise CompileError(
            "critical_path_limit", "Keep the critical path within 12 hours.", line
        )
    graph = {
        "schema": "stateaction.compiled-recipe/v1",
        "recipe": raw["recipe"],
        "meta": raw["meta"],
        "fanOut": fan_out,
        "topoOrder": order,
        "nodes": nodes,
        "license": {
            "commercialUse": not noncommercial,
            "nonCommercialModules": sorted(noncommercial),
        },
        "estimate": {
            "perClipJobUsdAtMax": dollars(cost["clip"]),
            "recordingNodesUsdAtMax": dollars(cost["recording"]),
            "criticalPathSecondsAtMax": critical,
        },
        "compiler": {"version": "1.0.0", "sdkVersion": "1.0.0"},
    }
    graph["recipeSha256"] = sha256(canonical_json(graph))
    graph["authoring"] = {
        "kind": "code",
        "files": [{"path": path, "sha256": sha256(source)}],
        "nodeSources": {node: f"{path}:{lineno}" for node, lineno in locations.items()},
    }
    validate(
        schema,
        graph,
        "invalid_compiled_graph",
        "Check the recipe shape against AUTHORING.md.",
        line,
    )
    return graph


def compile_recipe(path: Path, root: Path, catalog: dict) -> dict:
    source = read_source(path, root)
    if len(source) > SOURCE_LIMIT:
        raise CompileError(
            "source_too_large", "Keep the recipe source at or below 64 KiB."
        )
    schema = json.loads((root / SCHEMA).read_text())
    generated = bindings(catalog).encode("utf-8")
    compiled = []
    for _ in range(2):
        try:
            raw = json.loads(run_sandbox(source, generated))
            graph = compile_graph(
                raw, catalog, schema, path.relative_to(root).as_posix(), source
            )
            compiled.append(canonical_json(graph))
        except (
            KeyError,
            TypeError,
            ValueError,
            AttributeError,
            RecursionError,
            ArithmeticError,
        ) as exc:
            raise CompileError(
                "invalid_recipe",
                "Check the recipe shape and arguments against AUTHORING.md.",
            ) from exc
    if compiled[0] != compiled[1]:
        raise CompileError(
            "nondeterministic_recipe",
            "Remove state or nondeterministic computation from build.",
        )
    return json.loads(compiled[0])
