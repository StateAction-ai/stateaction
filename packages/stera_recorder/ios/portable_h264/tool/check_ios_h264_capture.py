#!/usr/bin/env python3
"""SA-52 portable iOS H.264 capture check (Linux simulation; not Apple/hardware evidence).

1. Builds and runs the Swift XCTest suite of the production h264 sources.
2. Runs `h264-capture-sim` twice, embedding (a) the published capture v1.1
   schemas and (b) a clearly labelled PROPOSED overlay that only widens the
   two Android-only fields an Apple producer needs.
3. Judges every scenario file with the unmodified SA-50 reference checker
   (`capture_conformance.check`, loaded from each contract directory):
   - published v1.1 must reject with E_SCHEMA_MALFORMED whose violations are
     *only* the known contract gap (Clocks clock_id const, FrameEvent
     native_timestamps keys). Any other violation or error fails.
   - the proposed overlay must accept, with frame/close facts equal to the
     controller's own summary.
4. Decodes each file's video access units with ffmpeg (when installed) and
   requires decoded frames == written frames, and that session_a/session_b
   IDRs carry only their own SPS.

Fails closed: a missing Swift toolchain is a failure unless --allow-missing-swift.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import shutil
import struct
import subprocess
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
PACKAGE = HERE.parent
REPO = PACKAGE.parents[3]
CAPTURE = REPO / "packages" / "contracts" / "capture"
DEFAULT_SWIFT = Path.home() / ".local/share/robotics-capture-tools/swift-dl/swift-6.1.2-RELEASE-ubuntu24.04/usr/bin/swift"

# PROPOSED revision fields (see ../README.md). Published v1.1 is never modified.
PROPOSED_CLOCK_IDS = ["android.elapsed_realtime", "apple.process_info_system_uptime"]
PROPOSED_NATIVE_KEYS = ["arkit_frame_timestamp_ns", "arkit_frame_timestamp_f64_bits"]
GAP_SUFFIXES = (
    "/recorder_transport/clock_id:const",
    "/native_timestamps:additionalProperties",
)


def fail(msg: str) -> None:
    print(f"FAIL: {msg}", file=sys.stderr)
    sys.exit(1)


def make_overlay(root: Path) -> Path:
    overlay = root / "capture-PROPOSED-ios-overlay"
    shutil.copytree(CAPTURE, overlay, ignore=shutil.ignore_patterns("golden", "__pycache__", "node_modules", ".build"))
    clocks = json.loads((overlay / "Clocks.schema.json").read_text())
    rt = clocks["properties"]["recorder_transport"]["properties"]
    assert rt["clock_id"] == {"const": "android.elapsed_realtime"}, "published Clocks.clock_id changed; update the overlay"
    rt["clock_id"] = {"enum": PROPOSED_CLOCK_IDS}
    (overlay / "Clocks.schema.json").write_text(json.dumps(clocks, indent=2) + "\n")
    frame = json.loads((overlay / "FrameEvent.schema.json").read_text())
    nt = frame["properties"]["native_timestamps"]["properties"]
    for key in PROPOSED_NATIVE_KEYS:
        assert key not in nt, "published FrameEvent already has the iOS key; drop the overlay"
        nt[key] = {"$ref": "#/$defs/int64Decimal"}
    (overlay / "FrameEvent.schema.json").write_text(json.dumps(frame, indent=2) + "\n")
    manifest = json.loads((overlay / "manifest.json").read_text())
    for name in manifest["files"]:
        manifest["files"][name] = hashlib.sha256((overlay / name).read_bytes()).hexdigest()
    (overlay / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")
    (overlay / "PROPOSED-NOT-PUBLISHED.txt").write_text("Test-only overlay generated by SA-52; not a published contract.\n")
    return overlay


CHECK_SNIPPET = r"""
import json, sys
sys.path.insert(0, sys.argv[1])
import capture_conformance as c
out = {}
for path in sys.argv[2:]:
    out[path] = c.check(open(path, "rb").read())
print(json.dumps(out))
"""


def run_checker(contract_dir: Path, files: list[Path]) -> dict:
    proc = subprocess.run(
        [sys.executable, "-I", "-c", CHECK_SNIPPET, str(contract_dir / "conformance" / "python"), *map(str, files)],
        capture_output=True, text=True, check=True,
    )
    return json.loads(proc.stdout)


def video_aus(path: Path) -> list[bytes]:
    data = path.read_bytes()
    topics, aus, off = {}, [], 8
    while off < len(data) - 8:
        op = data[off]
        (length,) = struct.unpack_from("<Q", data, off + 1)
        body = off + 9
        if op == 0x04:
            (cid,) = struct.unpack_from("<H", data, body)
            (n,) = struct.unpack_from("<I", data, body + 4)
            topics[cid] = data[body + 8: body + 8 + n].decode()
        elif op == 0x05:
            (cid,) = struct.unpack_from("<H", data, body)
            if topics.get(cid) == "/camera/rgb/video":
                aus.append(decode_video_data(data[body + 22: body + length]))
        off = body + length
    return aus


def decode_video_data(buf: bytes) -> bytes:
    i = 0

    def varint():
        nonlocal i
        v = s = 0
        while True:
            x = buf[i]; i += 1
            v |= (x & 0x7F) << s
            if x < 0x80:
                return v
            s += 7

    while i < len(buf):
        key = varint()
        if key & 7 == 2:
            n = varint()
            if key >> 3 == 3:
                return buf[i: i + n]
            i += n
        else:
            varint()
    raise ValueError("no data field")


def sps_of(au: bytes) -> list[bytes]:
    parts = au.split(b"\x00\x00\x00\x01")
    return [p for p in parts if p and p[0] & 31 == 7]


def ffmpeg_frames(stream: bytes, workdir: Path) -> int | None:
    ffprobe = shutil.which("ffprobe")
    if not ffprobe:
        return None
    path = workdir / "stream.h264"
    path.write_bytes(stream)
    out = subprocess.run(
        [ffprobe, "-v", "error", "-count_frames", "-select_streams", "v:0", "-show_entries",
         "stream=nb_read_frames", "-of", "csv=p=0", str(path)],
        capture_output=True, text=True, check=True,
    ).stdout.strip()
    return int(out)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--swift", default=os.environ.get("SWIFT_BIN", str(DEFAULT_SWIFT)))
    ap.add_argument("--allow-missing-swift", action="store_true")
    ap.add_argument("--require-ffmpeg", action="store_true")
    args = ap.parse_args()
    swift = shutil.which(args.swift) or (args.swift if Path(args.swift).exists() else None)
    if not swift:
        if args.allow_missing_swift:
            print("SKIP (not a pass): Swift toolchain unavailable")
            return
        fail(f"Swift toolchain not found ({args.swift}); set SWIFT_BIN")

    env = dict(os.environ, STATEACTION_REPO_ROOT=str(REPO))
    env.pop("STATEACTION_CAPTURE_CONTRACT_DIR", None)
    subprocess.run([swift, "test", "--package-path", str(PACKAGE)], check=True, env=env)

    with tempfile.TemporaryDirectory(prefix="sa52-ios-h264-") as tmp:
        root = Path(tmp)
        overlay = make_overlay(root)
        published_out, proposed_out = root / "published", root / "proposed"
        subprocess.run([swift, "run", "--package-path", str(PACKAGE), "h264-capture-sim", str(published_out)], check=True, env=env)
        subprocess.run([swift, "run", "--package-path", str(PACKAGE), "h264-capture-sim", str(proposed_out)], check=True,
                       env=dict(env, STATEACTION_CAPTURE_CONTRACT_DIR=str(overlay)))

        published_files = sorted(published_out.glob("*.mcap"))
        proposed_files = sorted(proposed_out.glob("*.mcap"))
        if len(published_files) < 10 or len(proposed_files) != len(published_files):
            fail("simulator did not write every scenario")

        for path, result in run_checker(CAPTURE, published_files).items():
            name = Path(path).stem
            violations = result["facts"].get("schema_violations", [])
            if result["outcome"] != "reject" or result["errors"] != ["E_SCHEMA_MALFORMED"]:
                fail(f"{name}: published v1.1 result {result['outcome']} {result['errors']} (expected only the contract gap)")
            unexpected = [v for v in violations if not v.endswith(GAP_SUFFIXES)]
            if unexpected or not violations:
                fail(f"{name}: unexpected published v1.1 violations {unexpected[:5]}")
            print(f"published-v1.1 {name}: rejected only on {len(violations)} known contract-gap pointers")

        decoded: dict[str, list[bytes]] = {}
        for path, result in run_checker(overlay, proposed_files).items():
            p = Path(path)
            name = p.stem
            expect = json.loads((p.parent / f"{name}.expect.json").read_text())
            if result["outcome"] != "accept":
                fail(f"{name}: proposed overlay rejected {result['errors']} {result['facts'].get('schema_violations', [])[:5]}")
            facts = result["facts"]
            counts = facts["frame_event_counts"]
            for key in ("acquired", "submitted", "written", "dropped"):
                if str(counts[key]) != expect[key]:
                    fail(f"{name}: {key} {counts[key]} != controller {expect[key]}")
            if facts["close_outcome"] != expect["outcome"] or str(facts["unresolved_frames"]) != expect["unresolved"]:
                fail(f"{name}: close {facts['close_outcome']}/{facts['unresolved_frames']} != {expect['outcome']}/{expect['unresolved']}")
            idrs = sum(1 for v in facts["video"] if v["idr"])
            if str(idrs) != expect["idr_messages"]:
                fail(f"{name}: idr {idrs} != {expect['idr_messages']}")
            aus = video_aus(p)
            if len(aus) != int(expect["written"]):
                fail(f"{name}: {len(aus)} video AUs != written {expect['written']}")
            for au in aus:
                if au.startswith(b"\x00\x00\x00\x01") and au[4] & 31 in (7,):
                    if [s.hex() for s in sps_of(au)] != [expect["sps_hex"]]:
                        fail(f"{name}: IDR carries foreign/stale SPS")
            decoded[name] = aus
            frames = ffmpeg_frames(b"".join(aus), root) if aus else 0
            if frames is None:
                if args.require_ffmpeg:
                    fail("ffprobe required but missing")
                note = "ffprobe unavailable (decode not checked)"
            else:
                if frames != len(aus):
                    fail(f"{name}: ffprobe decoded {frames} frames, expected {len(aus)}")
                note = f"ffprobe decoded {frames}/{len(aus)}"
            print(f"PROPOSED-overlay {name}: accept outcome={facts['close_outcome']} written={counts['written']} "
                  f"dropped={counts['dropped']} idr={idrs}; {note}")

        a, b = decoded.get("session_a"), decoded.get("session_b")
        if not a or not b or sps_of(a[0]) == sps_of(b[0]):
            fail("consecutive sessions did not use distinct parameter sets")
    print("OK: portable iOS H.264 capture simulation (Linux; no Apple framework, VideoToolbox or device evidence)")


if __name__ == "__main__":
    main()
