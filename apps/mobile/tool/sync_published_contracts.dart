// Embeds the published contract documents the app validates at runtime
// (packages/contracts/api) as exact UTF-8 text in a generated Dart file.
// Flutter cannot bundle assets from outside apps/mobile, so the bytes are
// copied verbatim; test/src/core/contracts/published_contracts_test.dart fails
// if they drift from the published files.
//
//   dart run tool/sync_published_contracts.dart          # regenerate
//   dart run tool/sync_published_contracts.dart --check  # exit 1 on drift
import "dart:convert";
import "dart:io";

const contracts = [
  "http.success-envelope.v1",
  "http.me.v1",
  "http.recording-create.v1",
  "http.recording-create.v2",
  "http.recording-registration.v1",
  "http.recording-registration.v2",
  "http.recording-seal.v1",
  "http.recording.v2",
  "http.upload-create.v1",
  "http.upload-plan.v1",
  "http.upload-transition.v1",
  "artifacts.recording-source.v1",
  "artifacts.recording-source.v2",
];
const output = "lib/src/core/contracts/published_contracts.g.dart";

String render(Directory api) {
  final catalogText = File("${api.path}/catalog.v6.json").readAsStringSync();
  final catalog = jsonDecode(catalogText) as Map<String, Object?>;
  final entries = catalog["contracts"]! as Map<String, Object?>;
  final common = catalog["common"]! as String;
  final allPaths = {
    common,
    for (final value in entries.values) (value! as Map)["schema"] as String,
  };
  final texts = {
    for (final path in allPaths)
      path: File("${api.path}/$path").readAsStringSync(),
  };
  final documents = {
    for (final entry in texts.entries)
      entry.key: jsonDecode(entry.value) as Map<String, Object?>,
  };
  final pathById = {
    for (final entry in documents.entries)
      entry.value[r"$id"]! as String: entry.key,
  };
  final needed = <String>{};
  late void Function(String) visit;
  void refs(Object? value) {
    if (value is Map) {
      final ref = value[r"$ref"];
      if (ref is String && !ref.startsWith("#")) {
        final path = pathById[ref.split("#").first];
        if (path == null) {
          throw StateError("Unpublished schema reference: $ref");
        }
        visit(path);
      }
      for (final child in value.values) {
        refs(child);
      }
    } else if (value is List) {
      for (final child in value) {
        refs(child);
      }
    }
  }

  visit = (path) {
    if (needed.add(path)) refs(documents[path]);
  };
  visit(common);
  for (final id in contracts) {
    final entry = entries[id] ?? (throw StateError(id));
    visit((entry as Map)["schema"] as String);
  }
  // Referenced schemas must also be catalog entries: ContractRegistry loads
  // their exact documents through the same resolver used by other runtimes.
  final ids =
      entries.keys
          .where((id) => needed.contains((entries[id]! as Map)["schema"]))
          .toList()
        ..sort();
  final selected = {for (final id in ids) id: entries[id]};
  final paths = needed.toList()..sort();
  final out = StringBuffer()
    ..writeln(
      "// GENERATED by tool/sync_published_contracts.dart. Do not edit.",
    )
    ..writeln("// Exact copies of packages/contracts/api documents.")
    ..writeln()
    ..writeln("/// Catalog name the entries below were taken from.")
    ..writeln("const publishedCatalogName = ${jsonEncode(catalog["catalog"])};")
    ..writeln()
    ..writeln("/// Subset of the published catalog with verbatim entries.")
    ..writeln("const publishedCatalogSubset = r'''")
    ..writeln(
      const JsonEncoder.withIndent("  ").convert({
        "catalog": catalog["catalog"],
        "common": common,
        "maxDepth": catalog["maxDepth"],
        "contracts": selected,
      }),
    )
    ..writeln("''';")
    ..writeln()
    ..writeln("/// Catalog-relative schema path -> exact published file text.")
    ..writeln("const publishedSchemaDocuments = <String, String>{");
  for (final path in paths) {
    final text = texts[path]!;
    if (text.contains("'''")) throw StateError("$path contains '''");
    out
      ..writeln("  ${jsonEncode(path)}: r'''")
      ..write(text)
      ..writeln("''',");
  }
  out.writeln("};");
  return out.toString();
}

void main(List<String> args) {
  final api = Directory("../../packages/contracts/api");
  final rendered = render(api);
  final file = File(output);
  if (args.contains("--check")) {
    final current = file.existsSync() ? file.readAsStringSync() : "";
    if (current != rendered) {
      stderr.writeln(
        "$output is stale; run dart run tool/sync_published_contracts.dart",
      );
      exitCode = 1;
    }
    return;
  }
  file
    ..createSync(recursive: true)
    ..writeAsStringSync(rendered);
}
