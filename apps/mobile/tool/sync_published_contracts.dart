// Embeds the published contract documents the app validates at runtime
// (packages/contracts/api) as exact UTF-8 text in a generated Dart file.
// Flutter cannot bundle assets from outside apps/mobile, so the bytes are
// copied verbatim; test/src/core/contracts/published_contracts_test.dart fails
// if they drift from the published files.
//
//   dart run tool/sync_published_contracts.dart          # regenerate
//   dart run tool/sync_published_contracts.dart --check  # exit 1 on drift
import "dart:convert";
import "dart:io";

const contracts = ["http.success-envelope.v1", "http.me.v1"];
const output = "lib/src/core/contracts/published_contracts.g.dart";

String render(Directory api) {
  final catalogText = File("${api.path}/catalog.v2.json").readAsStringSync();
  final catalog = jsonDecode(catalogText) as Map<String, Object?>;
  final entries = catalog["contracts"]! as Map<String, Object?>;
  final common = catalog["common"]! as String;
  final selected = <String, Object?>{
    for (final id in contracts) id: entries[id] ?? (throw StateError(id)),
  };
  final paths = [
    common,
    for (final id in contracts) (selected[id]! as Map)["schema"] as String,
  ];
  final out = StringBuffer()
    ..writeln(
      "// GENERATED by tool/sync_published_contracts.dart. Do not edit.",
    )
    ..writeln("// Exact copies of packages/contracts/api documents.")
    ..writeln()
    ..writeln("/// Catalog name the entries below were taken from.")
    ..writeln("const publishedCatalogName = ${jsonEncode(catalog["catalog"])};")
    ..writeln()
    ..writeln("/// Subset of the published catalog with verbatim entries.")
    ..writeln("const publishedCatalogSubset = r'''")
    ..writeln(
      const JsonEncoder.withIndent("  ").convert({
        "catalog": catalog["catalog"],
        "common": common,
        "maxDepth": catalog["maxDepth"],
        "contracts": selected,
      }),
    )
    ..writeln("''';")
    ..writeln()
    ..writeln("/// Catalog-relative schema path -> exact published file text.")
    ..writeln("const publishedSchemaDocuments = <String, String>{");
  for (final path in paths) {
    final text = File("${api.path}/$path").readAsStringSync();
    if (text.contains("'''")) throw StateError("$path contains '''");
    out
      ..writeln("  ${jsonEncode(path)}: r'''")
      ..write(text)
      ..writeln("''',");
  }
  out.writeln("};");
  return out.toString();
}

void main(List<String> args) {
  final api = Directory("../../packages/contracts/api");
  final rendered = render(api);
  final file = File(output);
  if (args.contains("--check")) {
    final current = file.existsSync() ? file.readAsStringSync() : "";
    if (current != rendered) {
      stderr.writeln(
        "$output is stale; run dart run tool/sync_published_contracts.dart",
      );
      exitCode = 1;
    }
    return;
  }
  file
    ..createSync(recursive: true)
    ..writeAsStringSync(rendered);
}
